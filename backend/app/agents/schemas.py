class FindingItem(BaseModel):
    """Individual evidence-backed finding, contradiction, or research gap."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    finding_id: str = Field(description="Unique finding identifier (e.g. 'find_01')")
    category: FindingCategory = Field(default=FindingCategory.FINDING, description="Category of finding")
