# 2. Researcher Agent Schemas
# =============================================================================

class ResearcherInput(BaseModel):
    """Input payload for the Researcher Agent."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    research_questions: list[str] = Field(min_length=1, description="Questions to find evidence for")
    search_queries: list[str] = Field(min_length=1, description="Search queries to execute")
    max_sources: int = Field(default=10, ge=1, le=30, description="Target unique sources to collect")
    preferred_domains: list[str] = Field(default_factory=list, max_length=10)
    excluded_domains: list[str] = Field(default_factory=list, max_length=10)
    extract_content: bool = Field(default=True, description="Whether to fetch full article text")

    @field_validator("preferred_domains", "excluded_domains")
    @classmethod
    def _normalize_domains(cls, domains: list[str]) -> list[str]:
        return [_normalize_domain_string(d) for d in domains if d.strip()]


class SourceItem(BaseModel):
    """Normalized evidence source collected by the Researcher Agent."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    source_id: str = Field(min_length=1, description="Deterministic source identifier (e.g. 'src_01')")
    title: str = Field(min_length=1, description="Original page title")
    url: str = Field(min_length=5, description="Original canonical URL of the external source")
    domain: str = Field(description="Normalized hostname of the source")
    published_date: str | None = Field(default=None, description="Publication date string if available")
    search_score: float | None = Field(default=None, ge=0.0, le=1.0, description="Search relevance score")
    extracted_content: str | None = Field(default=None, description="Extracted content or marker if unavailable")
    summary: str = Field(description="Objective factual summary of source evidence")
    related_questions: list[str] = Field(default_factory=list, description="Questions this source addresses")

    @field_validator("url")
    @classmethod
    def _validate_url(cls, v: str) -> str:
        parsed = urlparse(v)
        if not parsed.scheme or not parsed.netloc:
            raise ValueError(f"Invalid URL: {v}")
        return v


class ResearcherOutput(BaseModel):
    """Output summary and sources produced by the Researcher Agent."""

    model_config = ConfigDict(extra="forbid")

    sources: list[SourceItem] = Field(default_factory=list, description="Collected, validated sources")
    total_sources_found: int = Field(default=0, ge=0)
    deduplicated_count: int = Field(default=0, ge=0)
    filtered_count: int = Field(default=0, ge=0)
    queries_executed: list[str] = Field(default_factory=list)


