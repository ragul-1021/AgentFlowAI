class CitationValidation(BaseModel):
    """Verification record for an individual cited source."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    source_id: str = Field(description="Cited source ID")
    verdict: CitationVerdict = Field(description="Supported, partial, unsupported, or unchecked")
    explanation: str = Field(description="Detailed verification finding")


class EvidenceValidation(BaseModel):
    """Evaluation of whether a specific factual claim is supported by evidence."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    claim: str = Field(description="Specific claim evaluated")
    is_supported: bool = Field(description="Whether the claim is substantiated by cited sources")
    source_ids: list[str] = Field(default_factory=list, description="Supporting source IDs evaluated")
    notes: str = Field(default="", description="Analysis notes regarding the claim")


