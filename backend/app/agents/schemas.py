class ReportSection(BaseModel):
    """A subsection or chapter in the comprehensive report."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    heading: str = Field(min_length=2, description="Section heading")
    content: str = Field(min_length=10, description="Section body text with in-text source citations")
    subsections: list[ReportSection] = Field(default_factory=list)


class ReferenceItem(BaseModel):
    """Reference citation mapping back to a researcher source."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    source_id: str = Field(description="Exact source ID from Researcher")
    title: str = Field(description="Title of cited publication")
    url: str = Field(description="Preserved external canonical URL")
    citation_label: str = Field(default="", description="Citation mark in text (e.g. '[1]')")


class WriterOutput(BaseModel):
    """Complete structured research report written by the Writer Agent."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    title: str = Field(min_length=5, description="Final publication title")
    executive_summary: str = Field(min_length=30, description="Executive summary of the report")
    introduction: str = Field(min_length=20, description="Introduction and scope")
    methodology: str = Field(min_length=20, description="Research methodology explanation")
    main_sections: list[ReportSection] = Field(min_length=1, description="Core thematic sections")
    findings: str = Field(min_length=20, description="Consolidated findings narrative")
    discussion: str = Field(min_length=20, description="Implications, nuance, and synthesis")
    limitations: str = Field(min_length=10, description="Methodological and data limitations")
    conclusion: str = Field(min_length=20, description="Final conclusions and forward outlook")
    references: list[ReferenceItem] = Field(default_factory=list, description="Preserved bibliography")
    word_count: int = Field(ge=0, description="Calculated total word count")


