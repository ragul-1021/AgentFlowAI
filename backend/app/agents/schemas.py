    """Evaluation, quality audit, and recommendation produced by the Reviewer Agent."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    quality_score: int = Field(ge=0, le=100, description="Overall quality score (0-100)")
    completeness_score: int = Field(ge=0, le=100, description="Coverage of research objective (0-100)")
