    evidence_validations: list[EvidenceValidation] = Field(default_factory=list)
    accuracy_concerns: list[str] = Field(default_factory=list, description="Identified factual or citation concerns")
    missing_information: list[str] = Field(default_factory=list, description="Unaddressed research questions")
    revision_suggestions: list[str] = Field(default_factory=list, description="Actionable recommendations")
    approval_recommendation: bool = Field(
        default=False,
        description="Reviewer recommendation only; final approval strictly belongs to human user",
    )
    recommendation_notes: str = Field(min_length=5, description="Clear reasoning for the recommendation")
