# 1. Planner Agent Schemas
# =============================================================================

class PlannerInput(BaseModel):
    """Input parameters for the Planner Agent."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    topic: str = Field(min_length=5, max_length=500, description="Research topic")
    objective: str = Field(default="", max_length=4000, description="User's stated research goal")
    user_instructions: str | None = Field(default=None, max_length=4000, description="Optional constraints or preferences")
    depth: ResearchDepth = Field(default=ResearchDepth.STANDARD, description="Research depth tier")
    max_questions: int = Field(default=5, ge=1, le=10, description="Max questions to formulate")
    max_queries: int = Field(default=8, ge=1, le=20, description="Max search queries to formulate")


class PlannerOutput(BaseModel):
    """Validated structured plan generated by the Planner Agent."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    title: str = Field(min_length=3, max_length=300, description="Concise title for the research")
    refined_objective: str = Field(min_length=10, description="Sharpened, actionable research objective")
    research_questions: list[str] = Field(min_length=1, max_length=12, description="Targeted questions to answer")
    subtopics: list[str] = Field(min_length=1, max_length=15, description="Key subject areas to explore")
    search_queries: list[str] = Field(min_length=1, max_length=25, description="Focused, non-duplicated search queries")
    scope: list[str] = Field(default_factory=list, description="Boundaries and inclusions of research")
    exclusions: list[str] = Field(default_factory=list, description="Explicit out-of-scope topics or parameters")
    suggested_outline: list[str] = Field(min_length=3, description="Recommended outline sections for final report")

    @field_validator("search_queries")
    @classmethod
    def _dedup_queries(cls, queries: list[str]) -> list[str]:
        seen = set()
        deduped = []
        for q in queries:
            clean = q.strip()
            if clean and clean.lower() not in seen:
                seen.add(clean.lower())
                deduped.append(clean)
        if not deduped:
            raise ValueError("At least one non-empty search query is required.")
        return deduped

    @field_validator("research_questions")
    @classmethod
    def _dedup_questions(cls, questions: list[str]) -> list[str]:
        seen = set()
        deduped = []
        for q in questions:
            clean = q.strip()
            if clean and clean.lower() not in seen:
                seen.add(clean.lower())
                deduped.append(clean)
        if not deduped:
            raise ValueError("At least one research question is required.")
        return deduped


