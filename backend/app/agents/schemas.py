"""Input and output contract schemas for all five AgentFlow AI agents."""

from __future__ import annotations

import re
from typing import Any
from urllib.parse import urlparse
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from app.enums import (
    CitationVerdict,
    EvidenceStrength,
    FindingCategory,
    ReportFormat,
    ReportLength,
    ResearchDepth,
)

_HOSTNAME_RE = re.compile(
    r"^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$"
)


def _normalize_domain_string(val: str) -> str:
    domain = val.strip().lower().rstrip(".")
    if "://" in domain:
        domain = urlparse(domain).netloc.lower()
    if "/" in domain:
        domain = domain.split("/")[0]
    domain = domain.rstrip(".")
    if not _HOSTNAME_RE.match(domain):
        raise ValueError(f"Invalid domain format: '{val}'")
    return domain


