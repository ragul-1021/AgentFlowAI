NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def _uuid_pk() -> Mapped[Any]:
    return mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )


def _created_at() -> Mapped[datetime]:
    return mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )


def _enum_check(column: str, enum_cls: type, name: str) -> CheckConstraint:
    allowed = ", ".join(f"'{value}'" for value in values(enum_cls))
    return CheckConstraint(f"{column} IN ({allowed})", name=name)


def _json_list() -> Mapped[list[Any]]:
    return mapped_column(
        MutableList.as_mutable(JSONB),
        nullable=False,
        server_default=text("'[]'::jsonb"),
        default=list,
    )


def _json_object() -> Mapped[dict[str, Any]]:
    return mapped_column(
        MutableDict.as_mutable(JSONB),
        nullable=False,
        server_default=text("'{}'::jsonb"),
        default=dict,
    )


class ResearchTask(Base):
    __tablename__ = "research_tasks"

    id: Mapped[Any] = _uuid_pk()
    topic: Mapped[str] = mapped_column(String(500), nullable=False)
    description: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=text("''")
    )
    depth: Mapped[str] = mapped_column(
        String(16), nullable=False, server_default=text("'standard'")
    )
    source_target: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("10")
    )
    format: Mapped[str] = mapped_column(
        String(32), nullable=False, server_default=text("'general'")
    )
    length: Mapped[str] = mapped_column(
        String(16), nullable=False, server_default=text("'standard'")
    )
    preferred_domains: Mapped[list[Any]] = _json_list()
    excluded_domains: Mapped[list[Any]] = _json_list()

    status: Mapped[str] = mapped_column(
        String(32), nullable=False, server_default=text("'queued'")
    )
    stage: Mapped[str] = mapped_column(
        String(32), nullable=False, server_default=text("'queued'")
    )
    progress: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("0")
    )
    current_agent: Mapped[str | None] = mapped_column(String(32), nullable=True)

    revision_count: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("0")
    )
    total_tokens: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("0")
    )
    total_calls: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("0")
    )
    estimated_cost: Mapped[Decimal] = mapped_column(
        Numeric(12, 6), nullable=False, server_default=text("0")
    )

    error_code: Mapped[str | None] = mapped_column(String(64), nullable=True)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = _created_at()
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )
    started_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    plan: Mapped[ResearchPlan | None] = relationship(
        back_populates="task",
        cascade="all, delete-orphan",
        uselist=False,
        passive_deletes=True,
    )
    executions: Mapped[list[AgentExecution]] = relationship(
        back_populates="task", cascade="all, delete-orphan", passive_deletes=True
    )
    sources: Mapped[list[ResearchSource]] = relationship(
        back_populates="task", cascade="all, delete-orphan", passive_deletes=True
    )
    findings: Mapped[list[ResearchFinding]] = relationship(
        back_populates="task", cascade="all, delete-orphan", passive_deletes=True
    )
    reports: Mapped[list[ResearchReport]] = relationship(
        back_populates="task",
        cascade="all, delete-orphan",
        passive_deletes=True,
        order_by="ResearchReport.version",
    )
    events: Mapped[list[RunEvent]] = relationship(
        back_populates="task", cascade="all, delete-orphan", passive_deletes=True
    )

    __table_args__ = (
        _enum_check("depth", ResearchDepth, "depth_valid"),
        _enum_check("format", ReportFormat, "format_valid"),
        _enum_check("length", ReportLength, "length_valid"),
        _enum_check("status", TaskStatus, "status_valid"),
        _enum_check("stage", TaskStage, "stage_valid"),
        _enum_check("current_agent", AgentName, "current_agent_valid"),
        CheckConstraint("source_target BETWEEN 1 AND 100", name="source_target_range"),
        CheckConstraint("progress BETWEEN 0 AND 100", name="progress_range"),
        CheckConstraint("revision_count >= 0", name="revision_count_non_negative"),
        CheckConstraint("total_tokens >= 0", name="total_tokens_non_negative"),
        CheckConstraint("total_calls >= 0", name="total_calls_non_negative"),
        CheckConstraint("estimated_cost >= 0", name="estimated_cost_non_negative"),
        Index("ix_research_tasks_status_created_at", "status", desc("created_at")),
        Index("ix_research_tasks_created_at", desc("created_at")),
    )


